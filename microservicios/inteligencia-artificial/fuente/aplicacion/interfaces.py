"""Interfaces que define la aplicación y que implementa la infraestructura (regla de dependencia de Clear/Clean).

La aplicación nunca importa psycopg, httpx, Ollama ni scikit-learn: depende de estos contratos.
"""
from contextlib import AbstractAsyncContextManager
from datetime import datetime
from typing import Any, Protocol


class ModeloNoDisponible(Exception):
    """El modelo de lenguaje no respondió una salida usable: se usa la variante «no generativa».

    `motivo` distingue DESCONECTADO (no se pudo conectar), TIMEOUT (no terminó a tiempo), NO_DISPONIBLE (respondió con
    error, p. ej. modelo no instalado) e INCOMPATIBLE (respondió, pero cortado o fuera del esquema)."""

    def __init__(self, mensaje: str = "Modelo de lenguaje no disponible.", motivo: str = "NO_DISPONIBLE"):
        super().__init__(mensaje)
        self.motivo = motivo


class CursorFueraDeRango(Exception):
    """La fuente ya no reconoce la posición guardada: hay que releer desde 0 (la ingesta es idempotente)."""


class ServicioNoDisponible(Exception):
    pass


class RechazoDeServicio(Exception):
    def __init__(self, estado: int, cuerpo: dict):
        super().__init__(cuerpo.get("mensaje", f"HTTP {estado}"))
        self.estado, self.cuerpo = estado, cuerpo


class FuenteEventos(Protocol):
    async def eventos(self, desde: int) -> tuple[list[dict], int]: ...


class Catalogo(Protocol):
    async def variantes(self) -> list[dict]: ...


class InventarioEscritura(Protocol):
    async def version(self, variante: str) -> int: ...
    async def registrar_entrada(self, variante: str, cuerpo: dict, clave: str, token: str) -> dict: ...


class GestionInventario(Protocol):
    """Contrato propietario de Inventario para la gestión empresarial: la operación se ejecuta con el JWT del
    administrador y su Idempotency-Key; las reglas (SKU, versión, stock, calidad) se validan en Inventario."""
    async def ejecutar(self, operacion: str, token: str, *, ruta: dict | None = None, clave: str | None = None,
                       datos: dict | None = None, consulta: dict | None = None) -> dict: ...


class Perfiles(Protocol):
    async def medidas(self, token: str) -> dict: ...


class DirectorioClientes(Protocol):
    """Contrato interno de Clientes: nombre visible de cada cliente (sin contacto). Alimenta la proyección `clientes`."""
    async def nombres(self, clientes: list[str]) -> list[dict]: ...


class RepositorioAnalitica(Protocol):
    async def posicion(self, fuente: str) -> int: ...
    async def reiniciar(self, fuente: str) -> None: ...
    async def aplicar_eventos_ventas(self, eventos: list[dict], siguiente: int) -> int: ...
    async def aplicar_eventos_inventario(self, eventos: list[dict], siguiente: int) -> int: ...
    async def reemplazar_existencias(self, variantes: list[dict]) -> None: ...
    async def clientes_de_pedidos(self) -> list[str]: ...
    async def guardar_nombres(self, nombres: list[dict]) -> None: ...
    async def consultar_reporte(self, consulta: dict) -> dict: ...
    async def marcar_al_dia(self, fuente: str) -> None: ...
    async def frescura(self) -> dict[str, datetime]: ...
    async def resumen_ventas(self, desde: datetime | None, agrupar_por: str | None, limite: int, metrica: str = "UNIDADES",
                             fin: datetime | None = None, filtros: dict | None = None, orden: str = "METRICA_DESC") -> dict: ...
    async def productos(self, limite: int) -> list[dict]: ...
    async def stock_bajo(self) -> list[dict]: ...
    async def alertas(self, limite: int) -> list[dict]: ...
    async def compras_por_cliente(self, ahora: datetime) -> list[dict]: ...
    async def guardar_reporte(self, reporte: dict) -> None: ...
    async def reportes(self, limite: int) -> list[dict]: ...
    async def reporte(self, identificador: str) -> dict | None: ...
    async def auditar(self, usuario: str, agente: str, herramienta: str, argumentos: Any, permitido: bool, resultado: str) -> None: ...
    async def auditoria(self, limite: int) -> list[dict]: ...
    async def variante(self, identificador: str) -> dict | None: ...
    async def guardar_propuesta(self, propuesta: dict) -> bool: ...
    async def propuestas(self, estado: str | None) -> list[dict]: ...
    async def propuesta(self, identificador: str) -> dict | None: ...
    async def reclamar_propuesta(self, identificador: str, cuerpo: dict) -> bool: ...
    async def resolver_propuesta(self, identificador: str, estado: str, resultado: dict, desde: tuple[str, ...]) -> bool: ...
    async def guardar_notificacion(self, notificacion: dict) -> bool: ...
    async def notificacion(self, evento: str) -> dict | None: ...
    async def notificaciones(self, estado: str | None) -> list[dict]: ...
    async def atender_notificacion(self, evento: str, usuario: str) -> None: ...


class RepositorioDemostracion(RepositorioAnalitica, Protocol):
    """El mismo modelo de lectura sobre el dataset sintético aislado, con sus metadatos y la segmentación entrenada."""
    async def metadatos(self) -> dict | None: ...
    async def conteos(self) -> dict[str, int]: ...
    async def segmentacion(self) -> dict | None: ...
    async def exportar_csv(self, nombre: str) -> bytes: ...


class ModeloLenguaje(Protocol):
    async def json(self, sistema: str, usuario: str, esquema: dict) -> str: ...
    async def conversar(self, mensajes: list[dict], herramientas: list[dict]) -> dict: ...


class SesionHerramientas(Protocol):
    async def listar(self) -> list[dict]: ...
    async def llamar(self, nombre: str, argumentos: dict) -> Any: ...


class Herramientas(Protocol):
    def sesion(self, agente: str, token: str) -> AbstractAsyncContextManager[SesionHerramientas]: ...


class Transcriptor(Protocol):
    async def transcribir(self, audio: bytes) -> str: ...


class ModeloTallas(Protocol):
    def probabilidades(self, vector: list[float]) -> dict[str, float]: ...
    def exportar(self) -> dict: ...


class Agrupador(Protocol):
    def agrupar(self, filas: list[list[float]]) -> tuple[list[int], list[list[float]], float | None]: ...
